"""Plane-parallel (local) bispectrum terms - NPP, GR1, GR2 and PNG - angle-dependent, for three tracers (tracer i at
x_i, as bk_mt's b1/xb1/yb1). Generated by mathwap (the sympy port of MathWAP) - edit the generator, not this file. They
do not depend on the LOS; r, s are taken for the same signature as the wide-separation forms. PNG1 is the part linear
in fNL (bk's Loc, Eq, Orth), PNG3 every power of the tree, the primordial bispectrum on Gaussian legs (bk_mt's); the
shape - alpha, b01, b11, B_Phi - is a keyword when they are evaluated.

Laid out as bk/WS_.py: each block is its (k1, k2) permutation as coefficients of mu1^a mu2^b, methods of <block>_coef
(python -m cosmo_wap.bk.c_compile PP_), evaluated once per triangle and projected exactly onto any (l, m) (_lm); with
FoG angular_integrate.ylm integrates the angle-dependent B numerically. bk's and bk_mt's NPP, GR1, GR2, Loc, Eq and Orth
keep their analytic multipoles and get l4 and the m > 0 ones from here; bk_mt's, which have none, their ylm too (bk's
keep their own: 16 nodes, ~9x faster with FoG than n=24 here, but a few % off at l4, m4)."""
from functools import lru_cache as _lru_cache
from math import comb

import numpy as np
from scipy.special import sph_harm_y

from cosmo_wap.lib.angular_integrate import ylm as _ylm_num

_T = ("", "x", "y")
_PERMS = ((1, 2, 3), (1, 3, 2), (2, 3, 1))
_TRACER = ('b1', 'bd1', 'bdd1', 'b2', 'bd2', 'bdd2', 'g2', 'gd2', 'gdd2', 'gr1', 'grd1', 'grdd1', 'gr2', 'grd2', 'grdd2', 'beta6', 'betad6', 'betadd6', 'beta7', 'betad7', 'betadd7', 'beta8', 'betad8', 'betadd8', 'beta9', 'betad9', 'betadd9', 'beta10', 'betad10', 'betadd10', 'beta11', 'betad11', 'betadd11', 'beta12', 'betad12', 'betadd12', 'beta13', 'betad13', 'betadd13', 'beta14', 'betad14', 'betadd14', 'beta15', 'betad15', 'betadd15', 'beta16', 'betad16', 'betadd16', 'beta17', 'betad17', 'betadd17', 'beta18', 'betad18', 'betadd18', 'beta19', 'betad19', 'betadd19', 'b01', 'bd01', 'bdd01', 'b11', 'bd11', 'bdd11')  # tracer-dependent inputs, without the tracer prefix


def _inputs(cosmo_funcs, k1, k2, k3, theta, zz, RR, GR, shape=None, fNL=1, **kwargs):
    """the physical legs' inputs, in CosmoWAP's names - with shape, a PNG block's too: b01 and b11 per tracer,
    phi_i = k_i^alpha/M(k_i) and Bphi = M1 M2 M3 B_Phi/D^3 at unit fNL, as numeric_mu.kernels and numeric_mu.bk"""
    k1, k2, k3, theta, Pk1, Pk2, Pk3, Pkd1, Pkd2, Pkd3, Pkdd1, Pkdd2, Pkdd3, d, K, C, f, D1, _, _, _ = cosmo_funcs.get_params(k1, k2, k3, theta, zz)
    p = dict(k1=k1, k2=k2, k3=k3, Pk1=Pk1, Pk2=Pk2, Pk3=Pk3, Pkd1=Pkd1, Pkd2=Pkd2, Pkd3=Pkd3, Pkdd1=Pkdd1, Pkdd2=Pkdd2,
             Pkdd3=Pkdd3, d=d, K=K, C=C, f=f, D1=D1)
    for i, T in enumerate(_T):
        tr = cosmo_funcs.survey[i]
        p[T + "b1"], p[T + "b2"], p[T + "g2"] = tr.b_1(zz), tr.b_2(zz), tr.g_2(zz)
        if RR:
            fd, Dd, gd2, bd2, bd1, fdd, Ddd, gdd2, bdd2, bdd1 = cosmo_funcs.get_derivs(zz, t_n=i)
            p.update(fd=fd, Dd=Dd, fdd=fdd, Ddd=Ddd)
            p.update({T + "bd1": bd1, T + "bdd1": bdd1, T + "bd2": bd2, T + "bdd2": bdd2, T + "gd2": gd2, T + "gdd2": gdd2})
        if GR:
            be = cosmo_funcs.get_beta_funcs(zz, ti=i)
            p.update({T + "gr1": be[0], T + "gr2": be[1]} | {T + f"beta{j}": be[j - 4] for j in range(6, 20)})
            if RR:
                bd = cosmo_funcs.get_beta_derivs(zz, ti=i)
                p.update({T + "grd1": bd[0]} | {T + f"betad{j}": bd[j - 13] for j in range(14, 20)})
        if shape:
            p[T + "b01"], p[T + "b11"] = cosmo_funcs.get_PNG_bias(zz, i, shape)
    if shape:
        from cosmo_wap.numeric_mu.bk import get_B_prim
        from cosmo_wap.numeric_mu.kernels import K1, M_tail

        shape_fNL = kwargs.get(f"fNL_{shape.lower()}")  # per-shape override, as the analytic classes
        p["fNL"] = fNL if shape_fNL is None else shape_fNL
        for i, k in enumerate((k1, k2, k3), 1):
            p[f"phi{i}"] = k**K1.PNG_ALPHA[shape]/M_tail(cosmo_funcs, k, zz)
        p["Bphi"] = get_B_prim([shape], cosmo_funcs, k1, k2, k3, zz)
    return p, theta


def _relabel(p, legs, r, s):
    """inputs for the (k1, k2) permutation with its leg i on the physical leg legs[i-1]"""
    q = dict(p)
    for i, L in enumerate(legs, 1):
        for n in ("k", "Pk", "Pkd", "Pkdd", "phi"):
            if f"{n}{L}" in p:
                q[f"{n}{i}"] = p[f"{n}{L}"]
        for n in _TRACER:
            if _T[L - 1] + n in p:
                q[_T[i - 1] + n] = p[_T[L - 1] + n]
    w = (r, s, 1 - r - s)
    q["r"], q["s"] = w[legs[0] - 1], w[legs[1] - 1]
    return q


def _coeffs(block, p):
    """{(a, b): coefficient of mu1^a mu2^b} - looked up on the class each call, so compiled kernels count"""
    cls = _BLOCKS[block][0]
    return {ab: getattr(cls, f"l{i}")(p) for i, ab in enumerate(_AB[block])}


def _prefactor(order, d):
    nws = order[0] + order[1]
    return 1j**(nws + order[2])/d**nws


def _powers(x, n):
    """[1, x, ..., x^n], each from the last"""
    out = [1, x]
    for _ in range(n - 1):
        out.append(out[-1]*x)
    return out[:n + 1]


def _B(block, mu, phi, cosmo_funcs, k1, k2, k3, theta, zz, r, s, **kwargs):
    """sum of the three permutations - coefficients first, so they are evaluated once per triangle. On the grid each
    permutation's powers of its two cosines are built once, and the terms summed as sum_a ma^a sum_b c_ab mb^b -
    c*ma**a*mb**b term by term was ~13x slower"""
    order = _BLOCKS[block][1]
    p, theta = _inputs(cosmo_funcs, k1, k2, k3, theta, zz, RR=order[1] > 0, GR=order[2] > 0, **kwargs)
    mu2 = mu*np.cos(theta) + np.sqrt(1 - mu**2)*np.sin(theta)*np.cos(phi)
    mus = (mu, mu2, -(p["k1"]*mu + p["k2"]*mu2)/p["k3"])
    tot = 0
    for legs in _PERMS:
        c = _coeffs(block, _relabel(p, legs, r, s))
        pa = _powers(mus[legs[0] - 1], max(a for a, _ in c))
        pb = _powers(mus[legs[1] - 1], max(b for _, b in c))
        rows = {}
        for (a, b), cab in c.items():
            rows[a] = rows.get(a, 0) + cab*pb[b]
        tot = tot + sum(pa[a]*row for a, row in rows.items())
    return _prefactor(order, p["d"])*tot


@_lru_cache(maxsize=None)
def _J(l, m, n, j):
    """int dOmega conj(Y_lm) mu^n (1-mu^2)^(j/2) cos^j(phi): polynomial in mu when nonzero, phi by hand"""
    if j < m or (j - m) % 2:
        return 0.0
    x, w = np.polynomial.legendre.leggauss((n + j + l)//2 + 2)
    mu_part = np.sum(w*x**n*(1 - x**2)**(j/2)*sph_harm_y(l, m, np.arccos(x), 0).real)
    return mu_part*2*np.pi*comb(j, (j - m)//2)/2**j


def _to_mu12(c, legs, k1, k2, k3):
    """{(a, b)} of mu_legs[0]^a mu_legs[1]^b -> {(p, q)} of mu1^p mu2^q, with mu3 = -(k1 mu1 + k2 mu2)/k3"""
    def power(leg, n):
        if leg < 3:
            return {(n, 0) if leg == 1 else (0, n): 1}
        u, v = -k1/k3, -k2/k3
        return {(i, n - i): comb(n, i)*u**i*v**(n - i) for i in range(n + 1)}
    out = {}
    for (a, b), val in c.items():
        for (p1, q1), x in power(legs[0], a).items():
            for (p2, q2), y in power(legs[1], b).items():
                out[p1 + p2, q1 + q2] = out.get((p1 + p2, q1 + q2), 0) + val*x*y
    return out


def _lm(block, l, m, cosmo_funcs, k1, k2, k3, theta, zz, r, s, **kwargs):
    """int dOmega conj(Y_lm) B, exactly - as angular_integrate.ylm, with mu2 = mu ct + sqrt(1-mu^2) st cos(phi)"""
    order = _BLOCKS[block][1]
    p, theta = _inputs(cosmo_funcs, k1, k2, k3, theta, zz, RR=order[1] > 0, GR=order[2] > 0, **kwargs)
    ct, st = np.cos(theta), np.sin(theta)
    tot = {}
    for legs in _PERMS:
        for key, val in _to_mu12(_coeffs(block, _relabel(p, legs, r, s)), legs, p["k1"], p["k2"], p["k3"]).items():
            tot[key] = tot.get(key, 0) + val
    out = 0
    for (a, b), val in tot.items():
        for j in range(b + 1):
            J = _J(l, m, a + b - j, j)
            if J:
                out = out + val*comb(b, j)*ct**(b - j)*st**j*J
    return _prefactor(order, p["d"])*out


def _ylm(block, l, m, cosmo_funcs, k1, k2, k3=None, theta=None, zz=0, r=0, s=0, sigma=None, n=24, **kwargs):
    """int dOmega conj(Y_lm) B for block ('WA1', ...): exact without FoG, numerical with it (n=24 reaches 1e-13)"""
    if sigma is None:
        return _lm(block, l, m, cosmo_funcs, k1, k2, k3, theta, zz, r, s, **kwargs)
    func = _BLOCKS[block][2]
    return _ylm_num(func, l, m, cosmo_funcs, k1, k2, k3, theta, zz, r, s, sigma=sigma, n=n, **kwargs)


def _lacks(cls, name):
    """no such method, or only add_empty_methods' zero stand-in"""
    return getattr(getattr(cls, name, None), "__name__", "empty_array_func") == "empty_array_func"


def _add_multipoles(cls, block, lmax=4, **fixed):
    """give cls a ylm and each lx/lxmy up to lmax it does not have yet - analytic ones (and a ylm) already there stay.
    A stand-in is replaced where the multipole can be nonzero; B has the parity of nws + ngr, so the other parity's stay.
    fixed are keywords every call gets - a PNG block's shape"""
    if not hasattr(cls, "ylm"):
        cls.ylm = staticmethod(lambda l, m, *args, **kwargs: _ylm(block, l, m, *args, **fixed, **kwargs))
    parity = sum(_BLOCKS[block][1]) % 2
    for l in range(lmax + 1):
        for m in range(l + 1):
            name = f"l{l}" + (f"m{m}" if m else "")
            if (not hasattr(cls, name)) if l % 2 != parity else _lacks(cls, name):
                meth = lambda cosmo_funcs, k1, k2, k3=None, theta=None, zz=0, r=0, s=0, sigma=None, l=l, m=m, **kw: _ylm(block, l, m, cosmo_funcs, k1, k2, k3, theta, zz, r, s, sigma, **fixed, **kw)
                setattr(cls, name, staticmethod(meth))
    return cls


def _multipole_class(block, lmax=4):
    """a class with ylm and every lx/lxmy of block - the multi-tracer terms"""
    return _add_multipoles(type(block, (), {"__doc__": f"{block}: multipoles of {_BLOCKS[block][2].__name__}"}), block, lmax)



class NPP_coef:
    """NPP, (k1, k2) permutation: l{i}(p) is the coefficient of mu1^a mu2^b with (a, b) = _AB['NPP'][i]"""
    def l0(p):
        D1, K, Pk1, Pk2, b1, k1, k2, k3, xb1, yb1, yb2, yg2 = (p['D1'], p['K'], p['Pk1'], p['Pk2'], p['b1'], p['k1'], p['k2'], p['k3'], p['xb1'], p['yb1'], p['yb2'], p['yg2'])
        x0 = 1/k1
        x1 = 1/k2
        x3 = k3**2
        x4 = x0**2
        x5 = 2*x4
        x6 = x1**2
        x7 = x3*x4 - 2
        x8 = k1**2
        x9 = k2**2*x4 - 2
        x10 = x6*x8 + x9
        return (D1**4*Pk1*Pk2*b1*xb1*(-yb1*(K*(x10 - x3*(x5 - x6*x7)) + x6*(-k3**4*x4 + x8) + x9) + 4*yb2 + 2*yg2*(x10 - x3*(x5 - x6*x7))))/4

    def l1(p):
        C, D1, K, Pk1, Pk2, b1, f, k1, k2, k3, xb1, yb1, yb2, yg2 = (p['C'], p['D1'], p['K'], p['Pk1'], p['Pk2'], p['b1'], p['f'], p['k1'], p['k2'], p['k3'], p['xb1'], p['yb1'], p['yb2'], p['yg2'])
        x0 = 1/k1
        x1 = 1/k2
        x2 = 1/k3
        x3 = x1**2
        x4 = k1**2
        x5 = k3**2
        x6 = x3*(x4 - 2*x5) - 2
        x7 = x2**2
        x8 = k2**2
        x9 = 2*xb1
        x10 = x3*x5
        x11 = x10 - 2
        return (D1**4*Pk1*Pk2*b1*f*(x0**2*(x5*(2*x11*yg2 - x9*(C - 1) - yb1*(K*x11 - x10)) + x8*(-x9*(C*(x7*x8 - 2) + 1) - yb1*(K + 1) + 2*yg2)) + 2*x6*yg2 - x9*(C*(x7*(x4 - 2*x8) - 2) + 1) + yb1*(-K*x6 - x3*x4 + 4*xb1 + 2) + 4*yb2))/4

    def l2(p):
        C, D1, Pk1, Pk2, b1, f, k1, k2, k3, yb1 = (p['C'], p['D1'], p['Pk1'], p['Pk2'], p['b1'], p['f'], p['k1'], p['k2'], p['k3'], p['yb1'])
        x0 = 1/k1
        x2 = 1/k3
        x3 = x0**2
        x4 = k2**2
        x5 = k3**2
        x6 = x2**2
        return (-D1**4*Pk1*Pk2*b1*f**2*(C*(k1**2*x6 + x3*x5 - x4*(2*x3 + x6*(-x3*x4 + 2)) - 2) + x3*(x4 - x5) - 2*yb1 + 1))/2

    def l3(p):
        C, D1, Pk1, Pk2, b1, f, k1, k2, k3, xb1, yb1 = (p['C'], p['D1'], p['Pk1'], p['Pk2'], p['b1'], p['f'], p['k1'], p['k2'], p['k3'], p['xb1'], p['yb1'])
        x0 = 1/k1
        x1 = 1/k2
        x2 = 1/k3
        x3 = yb1 - 1
        x4 = k3**2
        x5 = x2**2
        return (D1**4*Pk1*Pk2*b1*f*xb1*(C*(k1*(2*x1 - x5*(k1**2*x1 - 2*k2)) - x0*(k2*(k2**2*x5 - 2) + x1*x4)) + k2*x0*x3 + x1*(k1*x3 + x0*x4)))

    def l4(p):
        C, D1, Pk1, Pk2, b1, f, k1, k2, k3, xb1, yb1 = (p['C'], p['D1'], p['Pk1'], p['Pk2'], p['b1'], p['f'], p['k1'], p['k2'], p['k3'], p['xb1'], p['yb1'])
        x0 = 1/k1
        x1 = 1/k2
        x2 = 1/k3
        x3 = x2**2
        x4 = 1 - yb1
        return (D1**4*Pk1*Pk2*b1*f**2*(k1*(2*C*k2*x3 - x1*(C*(k1**2*x3 - 2) + x4)) - x0*(k2*(C*(k2**2*x3 - 2) + x4 - xb1) + k3**2*x1*(C - 1))))

    def l5(p):
        D1, Pk1, Pk2, b1, f, k1, k2 = (p['D1'], p['Pk1'], p['Pk2'], p['b1'], p['f'], p['k1'], p['k2'])
        x0 = 1/k1
        return (D1**4*Pk1*Pk2*b1*f**3*k2*x0)

    def l6(p):
        C, D1, K, Pk1, Pk2, b1, f, k1, k2, k3, xb1, yb1, yb2, yg2 = (p['C'], p['D1'], p['K'], p['Pk1'], p['Pk2'], p['b1'], p['f'], p['k1'], p['k2'], p['k3'], p['xb1'], p['yb1'], p['yb2'], p['yg2'])
        x0 = 1/k1
        x1 = 1/k2
        x2 = 1/k3
        x3 = x0**2
        x4 = k2**2
        x5 = k3**2
        x6 = x3*(x4 - 2*x5) - 2
        x7 = x2**2
        x8 = k1**2
        x9 = 2*b1
        x10 = x3*x5
        x11 = x10 - 2
        return (D1**4*Pk1*Pk2*f*xb1*(x1**2*(x5*(2*x11*yg2 - x9*(C - 1) - yb1*(K*x11 - x10)) + x8*(-x9*(C*(x7*x8 - 2) + 1) - yb1*(K + 1) + 2*yg2)) + 2*x6*yg2 + x9*(C*(x7*(-x4 + 2*x8) + 2) - 1) + yb1*(-K*x6 + 4*b1 - x3*x4 + 2) + 4*yb2))/4

    def l7(p):
        C, D1, K, Pk1, Pk2, b1, f, k1, k2, k3, xb1, yb1, yb2, yg2 = (p['C'], p['D1'], p['K'], p['Pk1'], p['Pk2'], p['b1'], p['f'], p['k1'], p['k2'], p['k3'], p['xb1'], p['yb1'], p['yb2'], p['yg2'])
        x0 = 1/k1
        x1 = 1/k2
        x2 = 1/k3
        x3 = x0**2
        x4 = k2**2
        x5 = k3**2
        x6 = x3*(x4 - 2*x5) - 2
        x7 = x2**2
        x8 = k1**2
        x9 = 2*b1
        x10 = -4*b1
        x11 = x3*x4 - 2
        x12 = x3*x5
        x13 = x7*x8 - 2
        x14 = x12 - 2
        return (D1**4*Pk1*Pk2*f**2*(x1**2*(x5*(2*x14*yg2 - x9*(C - 1) - yb1*(K*x14 - x12)) + x8*(-x9*(C*x13 + 1) - yb1*(K + 1) + 2*yg2)) + 2*x6*yg2 + x9*(C*(x7*(-x4 + 2*x8) + 2) - 1) - 2*xb1*(C*(x12 + x13 - x4*(-x11*x7 + 2*x3)) + x10 + x3*(x4 - x5) - 2*yb1 + 1) + yb1*(-K*x6 - x10 - x11) + 4*yb2))/4

    def l8(p):
        C, D1, Pk1, Pk2, b1, f, k1, k2, k3, yb1 = (p['C'], p['D1'], p['Pk1'], p['Pk2'], p['b1'], p['f'], p['k1'], p['k2'], p['k3'], p['yb1'])
        x0 = 1/k1
        x2 = 1/k3
        x3 = x0**2
        x4 = k2**2
        x5 = k3**2
        x6 = x2**2
        return (-D1**4*Pk1*Pk2*f**3*(C*(k1**2*x6 + x3*x5 - x4*(2*x3 + x6*(-x3*x4 + 2)) - 2) - 4*b1 + x3*(x4 - x5) - 2*yb1 + 1))/2

    def l9(p):
        C, D1, Pk1, Pk2, b1, f, k1, k2, k3, xb1, yb1 = (p['C'], p['D1'], p['Pk1'], p['Pk2'], p['b1'], p['f'], p['k1'], p['k2'], p['k3'], p['xb1'], p['yb1'])
        x0 = 1/k1
        x1 = 1/k2
        x2 = 1/k3
        x3 = x2**2
        x4 = 1 - yb1
        return (D1**4*Pk1*Pk2*f**2*xb1*(k2*(2*C*k1*x3 - x0*(C*(k2**2*x3 - 2) + x4)) - x1*(k1*(C*(k1**2*x3 - 2) - b1 + x4) + k3**2*x0*(C - 1))))

    def l10(p):
        C, D1, Pk1, Pk2, b1, f, k1, k2, k3, xb1, yb1 = (p['C'], p['D1'], p['Pk1'], p['Pk2'], p['b1'], p['f'], p['k1'], p['k2'], p['k3'], p['xb1'], p['yb1'])
        x0 = 1/k1
        x1 = 1/k2
        x2 = 1/k3
        x3 = x2**2
        x4 = 1 - yb1
        return (D1**4*Pk1*Pk2*f**3*(k2*(2*C*k1*x3 - x0*(C*(k2**2*x3 - 2) + x4 - xb1)) - x1*(k1*(C*(k1**2*x3 - 2) - b1 + x4) + k3**2*x0*(C - 1))))

    def l11(p):
        D1, Pk1, Pk2, f, k1, k2 = (p['D1'], p['Pk1'], p['Pk2'], p['f'], p['k1'], p['k2'])
        x0 = 1/k1
        return (D1**4*Pk1*Pk2*f**4*k2*x0)

    def l12(p):
        C, D1, Pk1, Pk2, f, k1, k2, k3, xb1, yb1 = (p['C'], p['D1'], p['Pk1'], p['Pk2'], p['f'], p['k1'], p['k2'], p['k3'], p['xb1'], p['yb1'])
        x1 = 1/k2
        x2 = 1/k3
        x3 = x1**2
        x4 = k1**2
        x5 = k3**2
        x6 = x2**2
        return (D1**4*Pk1*Pk2*f**2*xb1*(C*(-k2**2*x6 - x3*x5 + x4*(2*x3 - x6*(x3*x4 - 2)) + 2) - x3*(x4 - x5) + 2*yb1 - 1))/2

    def l13(p):
        C, D1, Pk1, Pk2, f, k1, k2, k3, xb1, yb1 = (p['C'], p['D1'], p['Pk1'], p['Pk2'], p['f'], p['k1'], p['k2'], p['k3'], p['xb1'], p['yb1'])
        x1 = 1/k2
        x2 = 1/k3
        x3 = x1**2
        x4 = k1**2
