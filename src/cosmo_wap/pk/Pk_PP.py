"""The plane-parallel power spectrum terms - NPP, GR1, GR2 and the PNG ones - with every multipole to l = 6, the FoG-damped
ones through 1F1 moments. Generated by mathwap (the sympy port of MathWAP) - edit the generator, not this file.

_add_multipoles puts them on CosmoWAP's classes - pk/Pk_0.py's NPP, GR1 and GR2, which keep their own mu and l, and
pk/PNG.py's Loc, Eq and Orth, which take those from here too - see pk.combined. The classes here are private, so the
package's glob does not export them over CosmoWAP's."""
import numpy as np
from scipy.special import hyp1f1

from cosmo_wap.lib.angular_integrate import legendre
from cosmo_wap.lib.utils import add_empty_methods_pk


def _G(n, a):
    """int_{-1}^{1} mu^n exp(-(a mu)^2/2) dmu - the FoG moments; in 1F1 rather than erf, which cancels badly at small a"""
    return 2/(n + 1)*hyp1f1((n + 1)/2, (n + 3)/2, -a**2/2)

@add_empty_methods_pk('l1','l3','l5')
class _NPP:
    @staticmethod
    def mu(mu,cosmo_funcs,k1,zz=0,t=0):
        Pk,f,D1,b1,xb1 = cosmo_funcs.unpack_pk(k1,zz)
        x0 = f*mu**2
        expr = D1**2*Pk*(b1*xb1 + x0*(b1 + x0 + xb1))
        return expr

    @staticmethod
    def l(l,cosmo_funcs, k1, zz=0, t=0, sigma=None,n_mu=16):
        """Returns lth multipole with numeric mu integration over P(k,mu) power spectra"""
        return legendre(_NPP.mu,l,cosmo_funcs, k1, zz, t=t, sigma=sigma,n_mu=n_mu)

    ################################### Regular Multipoles #############################################################

    @staticmethod
    def l0(cosmo_funcs,k1,zz=0,t=0,sigma=None):
        Pk,f,D1,b1,xb1 = cosmo_funcs.unpack_pk(k1,zz)

        if sigma is not None:
            a = k1*sigma
            expr = D1**2*Pk*(b1*xb1*_G(0, a) + f**2*_G(4, a) + f*(b1 + xb1)*_G(2, a))/2
        else:
            expr = D1**2*Pk*(b1*xb1 + f*(5*b1 + 3*f + 5*xb1)/15)

        return expr

    @staticmethod
    def l2(cosmo_funcs,k1,zz=0,t=0,sigma=None):
        Pk,f,D1,b1,xb1 = cosmo_funcs.unpack_pk(k1,zz)

        if sigma is not None:
            a = k1*sigma
            x0 = 3*b1 - f
            expr = 5*D1**2*Pk*(-b1*xb1*_G(0, a) + 3*f**2*_G(6, a) + f*(x0 + 3*xb1)*_G(4, a) - (b1*f - x0*xb1)*_G(2, a))/4
        else:
            expr = 2*D1**2*Pk*f*(7*b1 + 6*f + 7*xb1)/21

        return expr

    @staticmethod
    def l4(cosmo_funcs,k1,zz=0,t=0,sigma=None):
        Pk,f,D1,b1,xb1 = cosmo_funcs.unpack_pk(k1,zz)

        if sigma is not None:
            a = k1*sigma
            x0 = b1*xb1
            x1 = 10*b1 - f
            expr = 9*D1**2*Pk*(35*f**2*_G(8, a) + 5*f*(7*b1 - 6*f + 7*xb1)*_G(6, a) + 3*x0*_G(0, a) + 3*(b1*f - x1*xb1)*_G(2, a) + (-3*f*(x1 + 10*xb1) + 35*x0)*_G(4, a))/16
        else:
            expr = 8*D1**2*Pk*f**2/35

        return expr

    @staticmethod
    def l6(cosmo_funcs,k1,zz=0,t=0,sigma=None):
        Pk,f,D1,b1,xb1 = cosmo_funcs.unpack_pk(k1,zz)

        if sigma is not None:
            a = k1*sigma
            x0 = b1*xb1
            x1 = 11*b1
            x2 = -f
            x3 = 21*b1 + x2
            expr = 13*D1**2*Pk*(231*f**2*_G(10, a) + 21*f*(-15*f + x1 + 11*xb1)*_G(8, a) - 5*x0*_G(0, a) - 5*(b1*f - x3*xb1)*_G(2, a) - 5*(-f*(x3 + 21*xb1) + 63*x0)*_G(4, a) + 21*(-5*f*(3*b1 + x2 + 3*xb1) + x1*xb1)*_G(6, a))/32
        else:
            expr = np.zeros_like(k1)

        return expr


@add_empty_methods_pk('l0','l2','l4','l6')
class _GR1:
    @staticmethod
    def mu(mu,cosmo_funcs,k1,zz=0,t=0):
        Pk,f,D1,b1,xb1,gr1,_,xgr1,_ = cosmo_funcs.unpack_pk(k1,zz,GR=True)
        expr = 1j*D1**2*Pk*mu*(-b1*xgr1 + f*mu**2*(gr1 - xgr1) + gr1*xb1)/k1
        return expr

    @staticmethod
    def l(l,cosmo_funcs, k1, zz=0, t=0, sigma=None,n_mu=16):
        """Returns lth multipole with numeric mu integration over P(k,mu) power spectra"""
        return legendre(_GR1.mu,l,cosmo_funcs, k1, zz, t=t, sigma=sigma,n_mu=n_mu)

    ################################### Regular Multipoles #############################################################

    @staticmethod
    def l1(cosmo_funcs,k1,zz=0,t=0,sigma=None):
        Pk,f,D1,b1,xb1,gr1,_,xgr1,_ = cosmo_funcs.unpack_pk(k1,zz,GR=True)

        if sigma is not None:
            a = k1*sigma
            expr = 3*1j*D1**2*Pk*(f*(gr1 - xgr1)*_G(4, a) - (b1*xgr1 - gr1*xb1)*_G(2, a))/(2*k1)
        else:
            x0 = 3*f
            expr = 1j*D1**2*Pk*(gr1*(x0 + 5*xb1) - xgr1*(5*b1 + x0))/(5*k1)

        return expr

    @staticmethod
    def l3(cosmo_funcs,k1,zz=0,t=0,sigma=None):
        Pk,f,D1,b1,xb1,gr1,_,xgr1,_ = cosmo_funcs.unpack_pk(k1,zz,GR=True)

        if sigma is not None:
            a = k1*sigma
            x0 = 3*f
            expr = 7*1j*D1**2*Pk*(5*f*(gr1 - xgr1)*_G(6, a) + 3*(b1*xgr1 - gr1*xb1)*_G(2, a) - (gr1*(x0 - 5*xb1) + xgr1*(5*b1 - x0))*_G(4, a))/(4*k1)
        else:
            expr = 2*1j*D1**2*Pk*f*(gr1 - xgr1)/(5*k1)

        return expr

    @staticmethod
    def l5(cosmo_funcs,k1,zz=0,t=0,sigma=None):
        Pk,f,D1,b1,xb1,gr1,_,xgr1,_ = cosmo_funcs.unpack_pk(k1,zz,GR=True)

        if sigma is not None:
            a = k1*sigma
            x0 = 3*f
            x1 = 10*f
            expr = 11*1j*D1**2*Pk*(63*f*(gr1 - xgr1)*_G(8, a) - 15*(b1*xgr1 - gr1*xb1)*_G(2, a) + 5*(gr1*(x0 - 14*xb1) + xgr1*(14*b1 - x0))*_G(4, a) - 7*(gr1*(x1 - 9*xb1) + xgr1*(9*b1 - x1))*_G(6, a))/(16*k1)
        else:
            expr = np.zeros_like(k1)

        return expr


