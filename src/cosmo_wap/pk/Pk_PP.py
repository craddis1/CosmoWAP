def _stand_in(meth):
    return getattr(meth, "__name__", "") == "empty_array_func"


def _add_multipoles(cls, src, lmax=6):
    """give cls every l{l} src has, and src's mu and l (any multipole, by numeric mu integration) where cls has none.
    The other parity's stand-ins stay - zero with FoG too"""
    for l in range(lmax + 1):
        meth = getattr(src, f"l{l}")
        if not _stand_in(meth):
            setattr(cls, f"l{l}", staticmethod(meth))
    for name in ("mu", "l"):
        if not hasattr(cls, name):
            setattr(cls, name, staticmethod(getattr(src, name)))


